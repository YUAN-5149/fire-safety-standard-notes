    if maj <= 30: return 'A'
    if maj <= 42: return 'N'
    if maj <= 60: return 'O'
    if maj <= 68: return 'H'
    if maj <= 81: return 'D'
    if maj == 97 and mi > 0: return 'G'
    if maj <= 97: return 'E'
    if maj <= 111: return 'F'
    if maj <= 132: return 'P'
    if maj <= 145: return 'R'
    if maj <= 156: return 'S'
    if maj <= 174: return 'T'
    if maj <= 179: return 'C'
    if maj <= 184: return 'I'
    if maj <= 187: return 'J'
    if maj <= 190: return 'K'
    if maj <= 192: return 'L'
    return 'U'

